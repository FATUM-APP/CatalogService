CREATE TABLE orders (
    id                                VARCHAR(36)     NOT NULL PRIMARY KEY,
    client_id                         VARCHAR(36)     NOT NULL,
    client_name                       VARCHAR(255)    NOT NULL,
    client_username                   VARCHAR(15)     NOT NULL,
    provider_id                       VARCHAR(36)     NOT NULL,
    booking                           TIMESTAMP       NOT NULL,
    service                           VARCHAR(36)     NOT NULL,
    negotiated_price                  NUMERIC(10,2)   NOT NULL,
    estimated_time                    INTEGER,
    delivery_city                     VARCHAR(50)     NOT NULL,
    delivery_state                    VARCHAR(50)     NOT NULL,
    country                           VARCHAR(50)     NOT NULL,
    residence                         VARCHAR(255)    NOT NULL,
    answers                           JSONB,
    requirements                      VARCHAR(500),
    order_status                      VARCHAR(15)     NOT NULL DEFAULT 'PENDING',
    reason                            VARCHAR(500),
    created_at                        TIMESTAMP       NOT NULL,
    delivery_started_at               TIMESTAMP,
    start_confirmed_by_customer       BOOLEAN,
    start_confirmed_by_provider       BOOLEAN,
    completion_confirmed_by_customer  BOOLEAN,
    completion_confirmed_by_provider  BOOLEAN,
    payment_confirmed_by_customer     BOOLEAN,
    payment_confirmed_by_provider     BOOLEAN,
    CONSTRAINT fk_order_service FOREIGN KEY (service) REFERENCES services (id)
);
